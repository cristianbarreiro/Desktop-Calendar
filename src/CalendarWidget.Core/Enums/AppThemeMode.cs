namespace CalendarWidget.Core.Enums;

/// <summary>
/// Specifies the application visual theme preference.
/// </summary>
public enum AppThemeMode
{
    /// <summary>
    /// Dark visual theme (default).
    /// </summary>
    Dark,

    /// <summary>
    /// Light visual theme.
    /// </summary>
    Light,

    /// <summary>
    /// Automatically match the Windows operating system theme.
    /// </summary>
    System,
}
