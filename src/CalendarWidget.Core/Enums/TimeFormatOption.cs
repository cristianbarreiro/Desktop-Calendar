namespace CalendarWidget.Core.Enums;

/// <summary>
/// Specifies the time display formatting preference.
/// </summary>
public enum TimeFormatOption
{
    /// <summary>
    /// 24-hour time format (e.g. 14:30:00).
    /// </summary>
    TwentyFourHour,

    /// <summary>
    /// 12-hour time format with AM/PM designator (e.g. 2:30:00 PM).
    /// </summary>
    TwelveHour,
}
